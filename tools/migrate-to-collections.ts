// ─── /blogg index: preserve the curated section order ───────────────────────
// The hand-written index grouped the cards into five editorial sections
// ("Latest", "Siste analyse", "Siste guide", "Guider", "Case studies og
// analyser"). Membership and order are editorial choices, not derivable from
// dates or tags, so they are lifted verbatim into src/data/. The four posts
// that were in sitemap.xml but had NO card at all (orphaned from /blogg since
// publication) are appended to "Latest" — an omission, not a decision.
{
  const idx = readFileSync(join(ROOT, "blogg/index.html"), "utf8");
  const sections: Array<{ title: string; routes: string[] }> = [];
  const secRe = /<p class="section-title">([\s\S]*?)<\/p>\s*<div class="post-grid">([\s\S]*?)<\/div>\s*(?=<p class="section-title">|<\/main>)/g;
  for (const m of idx.matchAll(secRe)) {
    const routes = [...m[2].matchAll(/<a href="([^"]+)" class="post-card">/g)].map((x) => x[1]);
    sections.push({ title: textOf(m[1]), routes });
  }
  const seen = new Set(sections.flatMap((s) => s.routes));
  const orphaned = readdirSync(outBlogg).map((f) => `/blogg/${f.replace(/\.html$/, "")}`)
    .filter((r) => !seen.has(r)).sort();
  if (sections.length === 0) throw new Error("blogg/index.html: parsed 0 sections");
  if (sections[0].title !== "Latest") throw new Error(`first section is "${sections[0].title}", expected "Latest"`);
  sections[0].routes.push(...orphaned);

  // Pierstop is the nav's "Metode-case" and is in sitemap.xml, but it never had
  // a card on /blogg either. Same omission class as the four posts above.
  const caseSection = sections.find((x) => x.title.startsWith("Case studies"));
  const caseOrphans = CASES.map((c) => c.route).filter((r) => !seen.has(r));
  if (caseSection) caseSection.routes.unshift(...caseOrphans);
  else if (caseOrphans.length) throw new Error("no case section to append to");

  const header = {
    label: textOf(idx.match(/<p class="page-label">([\s\S]*?)<\/p>/)?.[1] ?? "Blogg"),
    heading: textOf(idx.match(/<h1>([\s\S]*?)<\/h1>/)?.[1] ?? ""),
    sub: textOf(idx.match(/<p class="page-sub">([\s\S]*?)<\/p>/)?.[1] ?? ""),
    title: textOf(idx.match(/<title>([\s\S]*?)<\/title>/)?.[1] ?? ""),
    description: metaContent(idx, "name", "description") ?? "",
    canonical: idx.match(/<link rel="canonical" href="([^"]+)"/)?.[1] ?? "https://synligdigital.no/blogg",
    ogTitle: metaContent(idx, "property", "og:title") ?? "",
    ogDescription: metaContent(idx, "property", "og:description") ?? "",
  };
  const jsonLdIdx = [...idx.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)]
    .map((m) => JSON.parse(m[1]));

  const out = [
    "// GENERATED by tools/migrate-to-collections.ts — the curated section order",
    "// of the hand-written /blogg index, lifted verbatim (fase 3, 2026-08-09).",
    "// Editorial grouping: not derivable from dates or tags. Edit here, not in markup.",
    `export const BLOG_INDEX_HEADER = ${JSON.stringify(header, null, 2)} as const;`,
    "",
    `export const BLOG_INDEX_JSONLD: unknown[] = ${JSON.stringify(jsonLdIdx, null, 2)};`,
    "",
    "/** route -> section. Order within a section is the order it shipped in. */",
    `export const BLOG_INDEX_SECTIONS: ReadonlyArray<{ title: string; routes: readonly string[] }> = ${JSON.stringify(sections, null, 2)};`,
    "",
  ].join("\n");
  if (!DRY) writeFileSync(join(ROOT, "src/data/blog-index.ts"), out);
  console.log(`/blogg index: ${sections.length} curated sections, ${seen.size} carded + ${orphaned.length + caseOrphans.length} previously orphaned pages`);
}

