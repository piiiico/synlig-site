/**
 * ONE-SHOT PORT: hand-written blogg/*.html + case pages  →  Astro content
 * collections under src/content/.
 *
 * Kept in the repo as the record of *how* the port was done — the 36 blog
 * posts are the citation engine (we are the most-cited host in the category,
 * N=3 measurement 2026-08-08), so the content is MOVED, never rewritten. Every
 * transformation below is mechanical and reversible; nothing rephrases prose.
 *
 * What it does per file:
 *   1. reads head metadata (title/description/canonical/og/dates/tags)
 *   2. lifts every <script type="application/ld+json"> block out verbatim
 *   3. keeps the <!-- fact-source-allow… --> markers at the top of the SOURCE
 *      fragment (build.ts's fact-source gate reads them from src/content now)
 *   4. takes the body region, drops the duplicated site chrome (nav, footer,
 *      breadcrumb, h1, lead, meta row — all regenerated by the layout)
 *   5. splits the inline <style> into DUPLICATED boilerplate (dropped; the
 *      design system in src/styles/global.css owns it now) and BESPOKE
 *      per-post components (kept, with the dark palette remapped onto the
 *      light design tokens via the --art-* alias layer)
 *
 * Run:  cd /workspace/synlig-site && bun tools/migrate-to-collections.ts [--dry]
 */
