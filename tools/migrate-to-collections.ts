// ─── CSS: which selectors the design system now owns ────────────────────────
// Measured 2026-08-09: 295 395 bytes of inline CSS across 36 posts (avg 8 205 B
// ≈ 700 lines/file). 44 selectors appear in ≥18 of 36 files — pure duplication.
// Those are listed here and dropped; global.css carries them once.
const OWNED_EXACT = new Set([
  "*", "*::before", "*::after", ":root", "html", "body",
  "nav", "nav a", "footer", "footer a", "footer p",
  "h1", "h2", "h3", "h4", "h5", "p", "a", "a:hover", "strong", "em", "b", "i",
  "ul", "ol", "li", "ul li", "ol li", "blockquote", "code", "pre", "pre code",
  "table", "thead", "tbody", "tr", "th", "td", "img", "hr", "figure", "figcaption",
  "section", "article", "main", "header", "small",
]);
const OWNED_PREFIX = [
  ".nav-logo", ".nav-links", ".nav-cta",
  ".article-header", ".article-body", ".article-lead", ".article-meta",
  ".article-tag", ".post-meta", ".post-tag", ".post-lede", ".post-content",
  ".breadcrumb", ".meta-tag", ".meta-date", ".meta-author",
  ".audit-cta", ".callout", ".related-posts", ".related-grid", ".related-card",
  ".faq-item", ".faq-question", ".faq-answer", ".faq-arrow",
  ".key-answer", ".toc", ".cta-block", ".cta-btn", ".source-list",
  ".lead-form", ".content", ".container", ".wrap",
];
function ownedSelector(sel: string): boolean {
  const s = sel.trim();
  if (!s) return true;
  if (OWNED_EXACT.has(s)) return true;
  // descendant selectors rooted in an owned container: ".article-body h2", ".content p"
  for (const p of OWNED_PREFIX) {
    if (s === p || s.startsWith(p + " ") || s.startsWith(p + ":") ||
        s.startsWith(p + "::") || s.startsWith(p + ">") || s.startsWith(p + ".") ||
        s.startsWith(p + "-")) return true;
  }
  // "body h2", "article p" etc.
  if (/^(body|article|main|section|header|footer|nav)\s/.test(s)) return true;
  return false;
}

